import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compare} from './dist/core.mjs';
import {filterRelations,inspectionDetails} from './dist/review.mjs';
const p=JSON.parse(readFileSync('dist/example.json')),before=JSON.stringify(p),r=compare(p.assembly,p.coupons);
assert.equal(filterRelations(r.relations).length,6);
assert.equal(filterRelations(r.relations,'attention').length,3);
assert.equal(filterRelations(r.relations,'missing').length,1);
assert.equal(filterRelations(r.relations,'mismatches').length,2);
assert.equal(filterRelations(r.relations,'unknown').length,6);
const d=inspectionDetails(p.assembly,p.coupons.CD_wrong_slot,['C','D']);
assert.deepEqual(d.map(x=>[x.expected,x.actual,x.mismatch]),[[40,40,false],[5,5,false],[8,7,true]]);
assert.deepEqual(inspectionDetails(p.assembly,p.coupons.BC_wrong_spacing,['B','C']).map(x=>x.mismatch),[true,false,false]);
assert.equal(inspectionDetails(p.assembly,{},['A','B']).length,0);
assert.equal(inspectionDetails(p.assembly,undefined,['A','B']).length,0);
assert.equal(inspectionDetails(p.assembly,p.coupons.BCD,['B']).length,0);
assert.equal(JSON.stringify(p),before);
assert.equal(r.represented,5,'Filters do not change coverage');
p.coupons.CD_wrong_slot.D.slot_width=8;
assert.ok(inspectionDetails(p.assembly,p.coupons.CD_wrong_slot,['C','D']).every(d=>!d.mismatch));
p.coupons.CD_wrong_slot.D.slot_width=8+0.5e-9;
assert.ok(inspectionDetails(p.assembly,p.coupons.CD_wrong_slot,['C','D']).every(d=>!d.mismatch));
p.coupons.CD_wrong_slot.D.slot_width=8+2e-9;
assert.ok(inspectionDetails(p.assembly,p.coupons.CD_wrong_slot,['C','D']).some(d=>d.mismatch));
console.log('15 navigation/diagnostic assertions passed');
